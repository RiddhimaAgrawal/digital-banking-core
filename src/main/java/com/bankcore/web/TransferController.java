package com.bankcore.web;

import com.bankcore.domain.BankTransaction;
import com.bankcore.security.Caller;
import com.bankcore.service.TransferResult;
import com.bankcore.service.TransferService;
import com.bankcore.web.dto.Requests.TransferRequest;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.util.UUID;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.oauth2.server.resource.authentication.JwtAuthenticationToken;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestHeader;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/transfers")
@Tag(name = "Transfers", description = "Atomic, idempotent money transfers between accounts")
public class TransferController {

    private final TransferService transfers;

    public TransferController(TransferService transfers) {
        this.transfers = transfers;
    }

    @PostMapping
    @PreAuthorize("hasRole('CUSTOMER')")
    @Operation(summary = "Transfer money between two accounts",
            description = """
                    Atomic: one database transaction writes the transaction row, a debit and a credit ledger entry \
                    (which sum to zero), updates both balances and records the Kafka event, or nothing at all.

                    Idempotent: the Idempotency-Key header makes retries safe. Same key + same body returns the original \
                    result with HTTP 200 and header Idempotent-Replay: true. Same key + different body returns 422 \
                    IDEMPOTENCY_KEY_REUSED. Failed requests are not remembered, so they can be retried with the same key.""")
    public ResponseEntity<BankTransaction> transfer(
            @Parameter(description = "Unique key per logical transfer, e.g. a UUID generated by the client")
            @RequestHeader("Idempotency-Key") String idempotencyKey,
            @Valid @RequestBody TransferRequest request,
            JwtAuthenticationToken auth) {
        TransferResult result = transfers.transfer(idempotencyKey, request.sourceAccountNumber(),
                request.destinationAccountNumber(), request.amount(), request.description(), Caller.from(auth));
        return AccountController.respond(result);
    }

    @GetMapping("/{id}")
    @PreAuthorize("hasAnyRole('CUSTOMER','TELLER','ADMIN')")
    @Operation(summary = "Get a transaction (a participant, teller or admin)")
    public BankTransaction get(@PathVariable UUID id, JwtAuthenticationToken auth) {
        return transfers.getVisible(id, Caller.from(auth));
    }
}
